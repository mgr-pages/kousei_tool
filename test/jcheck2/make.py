# 成果物だけで見るチェックのうち、価格・計算・番号のチェックの模擬データ(文言はすべて架空)
#   python3 test/jcheck2/make.py 出力フォルダ   → seika.pdf(成果物 A4縦 2ページ)
#   1ページ目: 誤り(同じ品番の価格の食い違い・税込と税抜の計算・注記がない注記番号・丸数字の番号の飛び)
#   2ページ目: 誤りと間違えやすい正しい書き方(出たら余分な検出)。正解は test/jcheck2/gt.json
#   要るもの: reportlab と IPAゴシック
import sys, os
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

out = sys.argv[1] if len(sys.argv) > 1 else 'testdata/jcheck2'
os.makedirs(out, exist_ok=True)
pdfmetrics.registerFont(TTFont('ipag', '/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf'))
c = canvas.Canvas(os.path.join(out, 'seika.pdf'), pagesize=(595, 842))

def table(y, rows, head='希望小売価格（税込）'):
    """品番・品名・価格の表(セルごとに別の文字列)"""
    c.setFont('ipag', 10)
    for x, s in ((50, '品番'), (140, '品名'), (360, head)): c.drawString(x, y, s)
    for r in rows:
        y -= 20
        for x, s in zip((50, 140, 360), r): c.drawString(x, y, s)
    return y

def lines(y, xs, size=11, x=50, gap=24):
    c.setFont('ipag', size)
    for s in xs:
        c.drawString(x, y, s); y -= gap
    return y

# ---- 1ページ目: 誤り ----
c.setFont('ipag', 18); c.drawString(50, 790, '冬の家電カタログ　ご案内')
y = table(750, [('KX-2041A', 'そよかぜサーキュレーター', '12,800円'),
                ('KX-3150B', 'ぽかぽかセラミックヒーター', '18,480円'),
                ('HT-7720W', 'しっとりスチーム加湿器', '24,200円')])
y = lines(y - 40, [
    'KX-2041A　そよかぜサーキュレーター　12,800円（税込）',      # 表と同じ価格(正しい)
    'KX-3150B　ぽかぽかセラミックヒーター　18,840円（税込）',    # 表の価格(18,480円)と違う
    'スリムタワーエアコン　税込14,080円（税抜12,800円）',        # 正しい計算
    'ハンディクリーナー　税込19,800円（税抜18,500円）',          # 計算が合わない(税抜18,500円の税込は20,350円)
    'ベッドサイドライト　本体6,000円（税込6,500円）',            # 計算が合わない(10%でも8%でもない)
    'デスクファン　9,980円（税込10,978円）',                     # 正しい計算(言葉のない方は税抜)
    'ミニクッカー　12,800円＋税（14,000円）',                    # 計算が合わない(「＋税」の価格と言葉のない価格。14,080円のはず)
    '保証期間はお買い上げ日から1年間です※1。',                   # 注記あり
    '送料は全国一律です※2。設置の費用は別にかかります※4。',      # ※4 の注記がない
])
y = lines(y - 10, [
    '※1 保証の内容は保証書をご覧ください。',
    '※2 離島への配送は別料金です。',
    '※3 写真は使用イメージです。',
], size=8, gap=16)
y = lines(y - 20, [
    '①電源プラグを差し込みます。',
    '②運転ボタンを押します。',
    '④風量を選びます。',                                          # ③ がない
], size=10, gap=20)
c.showPage()

# ---- 2ページ目: 誤りと間違えやすい正しい書き方 ----
c.setFont('ipag', 18); c.drawString(50, 790, '冬の家電カタログ　お得な情報')
y = table(750, [('KX-2041A', 'そよかぜサーキュレーター', '12,800円'),           # 1ページ目と同じ価格
                ('PB-1290K', 'ハンディクリーナーミニ', '9,980円')])
y = lines(y - 40, [
    'HT-7720W　通常価格24,200円　特価19,800円',                  # 種類の違う価格(特価)は、表の税込の価格と比べない
    '対応機種：KX-2041A・KX-3150B　交換用フィルター　1,650円（税込）',   # 品番が2つの文の価格は、どちらの品番の価格ともしない
    'ウォールファン　税込12,800円（税抜11,637円）',               # 端数を切り上げた税抜(正しい)
    '軽減税率（8%）対象のお茶セット　税込3,240円（税抜3,000円）',   # 8%の記載があるページ(正しい)
    '送料550円、代金引換の手数料330円',                           # 税込・税抜の組ではない
    '容量は5*2=10Lです。',                                         # 掛け算の「*2」は注記番号ではない
    '※1個あたりの価格です。',                                    # 「※1個」は注記番号ではない
    '2023年モデルの在庫限りです※5。価格は変わることがあります※6。',   # 注記あり(番号は1ページ目から続く)
    '本体価格12,800円　税込5,500円以上のお買い上げで送料無料',    # 条件の金額(「以上」)は税込・税抜の組にしない
    'KX-2041Aをお買い上げの方に、専用スタンド（別売）もおすすめします。スタンドは3,300円です。',   # 品番から離れた価格は組にしない
], gap=24)
y = lines(y - 10, [
    '※5 在庫の数は店舗にお問い合わせください。',
    '※6 表示の価格は11月1日現在のものです。',
], size=8, gap=16)
# 2段組み: 左の段の見出し(品番だけ)と、同じ高さの右の段の長い文の価格は組にしない
c.setFont('ipag', 10); c.drawString(50, y - 20, 'LT-4410G'); c.drawString(300, y - 20, 'ご購入の方に、もれなく2,000円分のクーポンを差し上げます。')
y = table(y - 60, [('LT-4410G', 'ベッドサイドライト', '6,578円')])
# 丸数字の並び: PDFの中では①③②の順に書いた(見た目は①②③)。並びの順番でなく数で見るので、番号の飛びとしない
c.setFont('ipag', 10)
for dy, s in ((0, '①フィルターを外します。'), (40, '③よく乾かします。'), (20, '②水で洗います。')): c.drawString(50, y - 40 - dy, s)
y = lines(y - 100, [
    '■ 取り付け方',                                                # 見出しのあとは別の並び
    '①乾いたら取り付けます。',
    '②運転を始めます。',
    '①〜③の手順で行います。',                                     # 文の中の丸数字は箇条書きの番号としない
], size=10, gap=20)
c.showPage()
c.save()
print('ok', out)
