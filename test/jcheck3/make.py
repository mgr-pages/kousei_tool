# 成果物だけで見るチェックのうち、文法(文体の混在・二重否定・助詞や接続詞の重なりなど)と話し言葉(口語的な表現)の模擬データ(文言はすべて架空)
#   python3 test/jcheck3/make.py 出力フォルダ   → seika.pdf(成果物 A4縦 2ページ)
#   1ページ目: 誤り(1行に1つ)。2ページ目: 誤りと間違えやすい正しい書き方(出たら余分な検出)。正解は test/jcheck3/gt.json
#   1行が1つのまとまり(段落)になるよう、行の間をあける
#   要るもの: reportlab と IPAゴシック
import sys, os
from reportlab.pdfgen import canvas
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont

out = sys.argv[1] if len(sys.argv) > 1 else 'testdata/jcheck3'
os.makedirs(out, exist_ok=True)
pdfmetrics.registerFont(TTFont('ipag', '/usr/share/fonts/opentype/ipafont-gothic/ipag.ttf'))
c = canvas.Canvas(os.path.join(out, 'seika.pdf'), pagesize=(595, 842))

def page(title, xs):
    c.setFont('ipag', 16); c.drawString(50, 795, title)
    c.setFont('ipag', 10.5); y = 760
    for s in xs:
        c.drawString(50, y, s); y -= 23
    c.showPage()

